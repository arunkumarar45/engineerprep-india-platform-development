import { redirect } from "next/navigation";
import Link from "next/link";
import type { Metadata } from "next";

export const metadata: Metadata = {
  title: "Notifications",
  robots: { index: false, follow: false },
};
import { Bell, BellRing, Check, Settings } from "lucide-react";
import { PageHeader } from "@/components/layout";
import { Card, EmptyState } from "@/components/ui";
import { NotificationList } from "./NotificationList";
import { getNotifications } from "@/lib/queries";
import { getSessionUser } from "@/lib/auth";
import { relativeTime } from "@/lib/utils";

export default async function NotificationsPage() {
  const user = await getSessionUser();
  if (!user) redirect("/login?next=/notifications");

  const notifications = await getNotifications(user.id);
  const unread = notifications.filter((n) => !n.isRead).length;

  return (
    <>
      <PageHeader
        breadcrumb={[{ label: "Notifications" }]}
        title="Notifications"
        subtitle="VTU updates, job alerts, deadlines and learning reminders."
        actions={
          <div className="flex items-center gap-2">
            <span className="inline-flex items-center gap-1.5 rounded-lg bg-brand-50 px-3 py-2 text-xs font-bold text-brand-600">
              <BellRing className="size-3.5" /> {unread} unread
            </span>
            <Link
              href="/settings"
              className="inline-flex h-9 items-center gap-1.5 rounded-lg border border-line px-3 text-xs font-bold text-ink-900 hover:border-brand-300 hover:text-brand-600"
            >
              <Settings className="size-3.5" /> Preferences
            </Link>
          </div>
        }
      />

      {notifications.length === 0 ? (
        <EmptyState
          icon={<Bell className="size-6" />}
          title="No notifications"
          message="You're all caught up. New alerts will appear here."
          action={
            <Link
              href="/settings"
              className="inline-flex h-9 items-center rounded-lg bg-brand-500 px-4 text-sm font-bold text-white hover:bg-brand-600"
            >
              Manage preferences
            </Link>
          }
        />
      ) : (
        <NotificationList
          notifications={notifications.map((n) => ({
            id: n.id,
            type: n.type,
            title: n.title,
            body: n.body,
            linkUrl: n.linkUrl,
            isRead: n.isRead,
            createdAt: n.createdAt,
          }))}
        />
      )}

      <Card className="mt-5 p-4">
        <p className="flex items-center gap-2 text-xs text-ink-500">
          <Check className="size-3.5 text-success-500" />
          Notifications are generated by the automation engine and de-duplicated
          with idempotency keys — you will never receive the same alert twice.
          Latest activity {relativeTime(notifications[0]?.createdAt)}.
        </p>
      </Card>
    </>
  );
}

